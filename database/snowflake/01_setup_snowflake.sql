
-- =====================================================
-- SMART STORE DATA WAREHOUSE
-- CONFIGURACION INICIAL DE SNOWFLAKE
-- =====================================================

-- 1. BASE DE DATOS PRINCIPAL

CREATE DATABASE IF NOT EXISTS SMART_STORE_DW
    COMMENT = 'Data Warehouse de tienda online con almacen inteligente';

USE DATABASE SMART_STORE_DW;


-- 2. ESQUEMAS DE PROCESAMIENTO

CREATE SCHEMA IF NOT EXISTS RAW
    COMMENT = 'Datos originales provenientes de PostgreSQL e IoT';

CREATE SCHEMA IF NOT EXISTS STAGING
    COMMENT = 'Limpieza, validacion y transformacion de datos';

CREATE SCHEMA IF NOT EXISTS DW
    COMMENT = 'Modelo dimensional de hechos y dimensiones';

CREATE SCHEMA IF NOT EXISTS ANALYTICS
    COMMENT = 'Vistas, indicadores y reportes de negocio';


-- 3. WAREHOUSE PARA ETL/ELT

CREATE WAREHOUSE IF NOT EXISTS WH_SMART_ETL
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'Procesamiento de cargas y transformaciones';


-- 4. WAREHOUSE PARA ANALISIS

CREATE WAREHOUSE IF NOT EXISTS WH_SMART_ANALYTICS
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    COMMENT = 'Consultas analiticas y reportes';


-- 5. FORMATO DE ARCHIVOS JSON

CREATE FILE FORMAT IF NOT EXISTS RAW.FF_IOT_JSON
    TYPE = JSON
    STRIP_OUTER_ARRAY = FALSE
    COMPRESSION = AUTO;


-- 6. STAGE INTERNO PARA EVENTOS IOT

CREATE STAGE IF NOT EXISTS RAW.STG_IOT_EVENTS
    FILE_FORMAT = RAW.FF_IOT_JSON
    COMMENT = 'Archivos JSON de dispositivos simulados';


-- 7. TABLA DE EVENTOS ORIGINALES

CREATE TABLE IF NOT EXISTS RAW.IOT_EVENTS (
    EVENT_DATA VARIANT NOT NULL,
    SOURCE_FILE VARCHAR(500),
    LOAD_TIMESTAMP TIMESTAMP_LTZ
        DEFAULT CURRENT_TIMESTAMP()
)
COMMENT = 'Eventos originales JSON del almacen inteligente';


-- 8. CONTEXTO DE TRABAJO

USE WAREHOUSE WH_SMART_ETL;
USE DATABASE SMART_STORE_DW;
USE SCHEMA RAW;


-- 9. COMPROBACION DEL ENTORNO

SELECT
    CURRENT_DATABASE() AS DATABASE_ACTUAL,
    CURRENT_SCHEMA() AS SCHEMA_ACTUAL,
    CURRENT_WAREHOUSE() AS WAREHOUSE_ACTUAL;
