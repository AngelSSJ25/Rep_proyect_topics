USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_SMART_ETL;
USE DATABASE SMART_STORE_DW;
USE SCHEMA RAW;

-- Tabla central de ingesta desde PostgreSQL

CREATE TABLE IF NOT EXISTS RAW.POSTGRES_RECORDS (
    SOURCE_TABLE VARCHAR(100) NOT NULL,
    RECORD_ID VARCHAR(100) NOT NULL,
    RECORD_DATA VARIANT NOT NULL,
    SOURCE_UPDATED_AT TIMESTAMP_TZ,
    LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),

    PRIMARY KEY (SOURCE_TABLE, RECORD_ID)
);

-- Registro de ejecuciones ETL

CREATE TABLE IF NOT EXISTS RAW.ETL_EXECUTIONS (
    EXECUTION_ID VARCHAR(100),
    PROCESS_NAME VARCHAR(100),
    STARTED_AT TIMESTAMP_LTZ,
    FINISHED_AT TIMESTAMP_LTZ,
    STATUS VARCHAR(30),
    RECORDS_PROCESSED INTEGER,
    ERROR_MESSAGE VARCHAR(2000)
);