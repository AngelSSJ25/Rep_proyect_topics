USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_SMART_ANALYTICS;
USE DATABASE SMART_STORE_DW;
USE SCHEMA ANALYTICS;


-- =====================================================
-- 1. VENTAS MENSUALES
-- =====================================================

CREATE OR REPLACE VIEW ANALYTICS.V_VENTAS_MENSUALES AS
SELECT
    F.ANIO,
    F.MES,
    DATE_TRUNC('MONTH', F.FECHA)::DATE AS PERIODO,

    COUNT(DISTINCT V.PEDIDO_ID) AS PEDIDOS_TOTALES,

    COUNT(DISTINCT CASE
        WHEN V.ESTADO_PEDIDO = 'ENTREGADO'
        THEN V.PEDIDO_ID
    END) AS PEDIDOS_ENTREGADOS,

    SUM(V.IMPORTE_PEDIDO) AS IMPORTE_SOLICITADO,

    SUM(V.INGRESO_REALIZADO) AS INGRESOS,

    SUM(CASE
        WHEN V.ESTADO_PEDIDO = 'ENTREGADO'
        THEN V.COSTO_MERCANCIA
        ELSE 0
    END) AS COSTOS,

    SUM(V.MARGEN_REALIZADO) AS MARGEN_BRUTO

FROM DW.FACT_VENTAS V
JOIN DW.DIM_FECHA F
    ON V.FECHA_KEY = F.FECHA_KEY

GROUP BY F.ANIO, F.MES, PERIODO;


-- =====================================================
-- 2. PRODUCTOS MAS VENDIDOS
-- =====================================================

CREATE OR REPLACE VIEW ANALYTICS.V_PRODUCTOS_MAS_VENDIDOS AS
SELECT
    P.PRODUCTO_KEY,
    P.SKU,
    P.PRODUCTO,
    P.CATEGORIA,

    SUM(CASE
        WHEN V.ESTADO_PEDIDO = 'ENTREGADO'
        THEN V.CANTIDAD
        ELSE 0
    END) AS UNIDADES_VENDIDAS,

    SUM(V.INGRESO_REALIZADO) AS INGRESOS,

    SUM(V.MARGEN_REALIZADO) AS MARGEN_BRUTO,

    COUNT(DISTINCT CASE
        WHEN V.ESTADO_PEDIDO = 'ENTREGADO'
        THEN V.PEDIDO_ID
    END) AS PEDIDOS_ENTREGADOS

FROM DW.FACT_VENTAS V
JOIN DW.DIM_PRODUCTO P
    ON V.PRODUCTO_KEY = P.PRODUCTO_KEY

GROUP BY
    P.PRODUCTO_KEY,
    P.SKU,
    P.PRODUCTO,
    P.CATEGORIA;


-- =====================================================
-- 3. OPERACIONES POR ALMACEN
-- =====================================================

CREATE OR REPLACE VIEW ANALYTICS.V_OPERACIONES_ALMACEN AS
SELECT
    A.ALMACEN_KEY,
    A.ALMACEN,

    M.TIPO_MOVIMIENTO,

    COUNT(*) AS TOTAL_MOVIMIENTOS,

    SUM(M.CANTIDAD) AS UNIDADES_PROCESADAS,

    COUNT(DISTINCT M.PRODUCTO_KEY)
        AS PRODUCTOS_DIFERENTES,

    COUNT(M.EVENTO_IOT_ID)
        AS EVENTOS_IOT_ASOCIADOS

FROM DW.FACT_MOVIMIENTOS M
JOIN DW.DIM_ALMACEN A
    ON M.ALMACEN_KEY = A.ALMACEN_KEY

GROUP BY
    A.ALMACEN_KEY,
    A.ALMACEN,
    M.TIPO_MOVIMIENTO;


-- =====================================================
-- 4. TRAZABILIDAD DE EVENTOS IOT
-- =====================================================

CREATE OR REPLACE VIEW ANALYTICS.V_TRAZABILIDAD_IOT AS
SELECT
    M.MOVIMIENTO_ID,
    M.FECHA_MOVIMIENTO,
    M.PEDIDO_ID,

    P.SKU,
    P.PRODUCTO,

    A.ALMACEN,

    M.TIPO_MOVIMIENTO,
    M.CANTIDAD,

    M.REFERENCIA_EVENTO,
    M.EVENTO_IOT_ID,
    M.CLASIFICACION_IOT,

    D.CODIGO AS DISPOSITIVO,
    D.TIPO AS TIPO_DISPOSITIVO,

    UO.CODIGO_UBICACION AS UBICACION_ORIGEN,
    UD.CODIGO_UBICACION AS UBICACION_DESTINO

FROM DW.FACT_MOVIMIENTOS M

LEFT JOIN DW.DIM_PRODUCTO P
    ON M.PRODUCTO_KEY = P.PRODUCTO_KEY

LEFT JOIN DW.DIM_ALMACEN A
    ON M.ALMACEN_KEY = A.ALMACEN_KEY

LEFT JOIN DW.DIM_DISPOSITIVO D
    ON M.DISPOSITIVO_KEY = D.DISPOSITIVO_KEY

LEFT JOIN DW.DIM_UBICACION UO
    ON M.UBICACION_ORIGEN_KEY = UO.UBICACION_KEY

LEFT JOIN DW.DIM_UBICACION UD
    ON M.UBICACION_DESTINO_KEY = UD.UBICACION_KEY;


-- =====================================================
-- RESULTADO ANALITICO INICIAL
-- =====================================================

SELECT
    PERIODO,
    PEDIDOS_TOTALES,
    PEDIDOS_ENTREGADOS,
    INGRESOS,
    MARGEN_BRUTO
FROM ANALYTICS.V_VENTAS_MENSUALES
ORDER BY PERIODO;
